/// Scale words with their values, largest first. A count of crores can be larger than
/// 99, so the code reads that count with the same function.
const SCALES: [(u64, &str); 4] = [
    (10_000_000, "करोड़"),
    (100_000, "लाख"),
    (1000, "हज़ार"),
    (100, "सौ"),
];

pub(super) fn hi(n: u64) -> String {
    if n < 100 {
        return BELOW_100[n as usize].to_string();
    }
    let mut parts = Vec::new();
    let mut rest = n;
    for (scale, word) in SCALES {
        // Only crore can have a count of 100 or more. The other scales stay below 100.
        let count = rest / scale;
        if count > 0 {
            parts.push(format!("{} {word}", hi(count)));
            rest %= scale;
        }
    }
    if rest > 0 {
        parts.push(BELOW_100[rest as usize].to_string());
    }
    parts.join(" ")
}

