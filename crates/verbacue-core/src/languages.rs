/// The English name of a language code, from Whisper's table of about 100 languages
/// (for example "ja" gives "Japanese"). Unknown values are returned as they are, so the
/// model still gets something it may understand.
pub fn language_name(code: &str) -> String {
    LANGUAGES
        .iter()
        .find(|(c, _)| *c == code)
        .map_or_else(|| code.to_string(), |(_, name)| (*name).to_string())
}

/// All languages in Whisper's table, as (code, English name) pairs.
pub fn languages() -> &'static [(&'static str, &'static str)] {
    LANGUAGES
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn language_names_come_from_whisper() {
        assert_eq!(language_name("hu"), "Hungarian");
        assert_eq!(language_name("ja"), "Japanese");
        assert_eq!(language_name("sw"), "Swahili");
        assert_eq!(language_name("Klingon"), "Klingon");
        let all = languages();
        assert!(all.len() > 90);
        assert!(all.contains(&("hu", "Hungarian")));
    }
}
